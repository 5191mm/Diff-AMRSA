#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Generate Table 4-2: Basic quality statistics of molecules generated by the final model.

Inputs:
1. Generated molecule SDF
2. Training/reference CSV with a smiles column
3. Optional existing DOCX to append the table into

Outputs:
1. DOCX containing the English table
2. CSV table
3. JSON summary
"""

import argparse
import json
import math
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from rdkit import Chem, DataStructs, RDLogger
from rdkit.Chem import AllChem

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_CELL_VERTICAL_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt


RDLogger.DisableLog("rdApp.*")


TABLE_TITLE = "Table 4-2 Basic Quality Statistics of Molecules Generated by the Final Model"


def count_sdf_records(sdf_path: Path) -> int:
    text = sdf_path.read_text(encoding="utf-8", errors="ignore")
    count = text.count("$$$$")
    if count > 0:
        return count

    supplier = Chem.SDMolSupplier(str(sdf_path), sanitize=False, removeHs=False)
    return sum(1 for _ in supplier)


def strict_sanitize_sdf_mol(mol: Chem.Mol) -> Optional[Chem.Mol]:
    if mol is None:
        return None

    try:
        clean = Chem.Mol(mol)
        Chem.SanitizeMol(clean)
        smiles = Chem.MolToSmiles(clean, canonical=True)
        final_mol = Chem.MolFromSmiles(smiles)
        return final_mol
    except Exception:
        return None


def canonicalize_training_smiles(smiles: str) -> Optional[str]:
    if pd.isna(smiles):
        return None

    try:
        mol = Chem.MolFromSmiles(str(smiles), sanitize=False)
    except Exception:
        return None

    if mol is None:
        return None

    try:
        fragments = Chem.GetMolFrags(mol, asMols=True, sanitizeFrags=False)
        if fragments:
            def fragment_score(fragment: Chem.Mol):
                atoms = list(fragment.GetAtoms())
                has_carbon = int(any(atom.GetSymbol() == "C" for atom in atoms))
                heavy_atoms = sum(1 for atom in atoms if atom.GetAtomicNum() > 1)
                total_atoms = len(atoms)
                return has_carbon, heavy_atoms, total_atoms

            mol = sorted(fragments, key=fragment_score, reverse=True)[0]
    except Exception:
        pass

    try:
        Chem.SanitizeMol(mol)
        return Chem.MolToSmiles(mol, canonical=True)
    except Exception:
        return None


def load_training_smiles(training_csv: Path, smiles_col: str) -> set:
    df = pd.read_csv(training_csv)
    if smiles_col not in df.columns:
        raise ValueError(f"Column '{smiles_col}' was not found in {training_csv}")

    smiles_set = set()
    for smiles in df[smiles_col].dropna().astype(str):
        canonical = canonicalize_training_smiles(smiles)
        if canonical:
            smiles_set.add(canonical)

    return smiles_set


def load_generated_molecules(sdf_path: Path) -> Tuple[int, List[Chem.Mol], List[str], List[int]]:
    total_records = count_sdf_records(sdf_path)
    supplier = Chem.SDMolSupplier(str(sdf_path), sanitize=False, removeHs=False)

    valid_mols = []
    canonical_smiles = []
    connected_flags = []

    for raw_mol in supplier:
        mol = strict_sanitize_sdf_mol(raw_mol)
        if mol is None:
            continue

        try:
            smiles = Chem.MolToSmiles(mol, canonical=True)
        except Exception:
            continue

        try:
            fragments = Chem.GetMolFrags(mol)
            connected = 1 if len(fragments) == 1 else 0
        except Exception:
            connected = 0

        valid_mols.append(mol)
        canonical_smiles.append(smiles)
        connected_flags.append(connected)

    return total_records, valid_mols, canonical_smiles, connected_flags


def mean_pairwise_diversity(mols: List[Chem.Mol], max_pairs: int = 0, seed: int = 42) -> float:
    if len(mols) <= 1:
        return float("nan")

    fps = [
        AllChem.GetMorganFingerprintAsBitVect(mol, radius=2, nBits=2048)
        for mol in mols
    ]

    n = len(fps)
    total_pairs = n * (n - 1) // 2

    if max_pairs and total_pairs > max_pairs:
        rng = np.random.default_rng(seed)
        sims = []
        for _ in range(max_pairs):
            i, j = rng.choice(n, size=2, replace=False)
            sims.append(DataStructs.TanimotoSimilarity(fps[i], fps[j]))
        avg_similarity = float(np.mean(sims))
        return 1.0 - avg_similarity

    sims = []
    for i in range(1, n):
        sims.extend(DataStructs.BulkTanimotoSimilarity(fps[i], fps[:i]))

    avg_similarity = float(np.mean(sims)) if sims else float("nan")
    return 1.0 - avg_similarity


def safe_ratio(numerator: float, denominator: float) -> float:
    if denominator == 0:
        return float("nan")
    return float(numerator) / float(denominator)


def format_value(value, is_ratio: bool = False) -> str:
    if value is None:
        return "N/A"
    try:
        if isinstance(value, float) and math.isnan(value):
            return "N/A"
    except Exception:
        pass

    if is_ratio:
        return f"{float(value):.4f}"

    if isinstance(value, (int, np.integer)):
        return str(int(value))

    if isinstance(value, float):
        return f"{value:.4f}"

    return str(value)


def compute_quality_table(
    generated_sdf: Path,
    training_csv: Path,
    smiles_col: str,
    sampled_count: int,
    max_diversity_pairs: int,
    seed: int,
) -> Tuple[pd.DataFrame, Dict]:
    sdf_record_count, valid_mols, valid_smiles, connected_flags = load_generated_molecules(generated_sdf)

    if sampled_count <= 0:
        sampled_count = sdf_record_count

    training_smiles = load_training_smiles(training_csv, smiles_col)

    valid_count = len(valid_mols)
    connected_count = int(sum(connected_flags))
    unique_smiles = sorted(set(valid_smiles))
    unique_count = len(unique_smiles)

    novel_smiles = [smiles for smiles in unique_smiles if smiles not in training_smiles]
    novel_count = len(novel_smiles)

    unique_mols = []
    for smiles in unique_smiles:
        mol = Chem.MolFromSmiles(smiles)
        if mol is not None:
            unique_mols.append(mol)

    diversity = mean_pairwise_diversity(unique_mols, max_pairs=max_diversity_pairs, seed=seed)

    metrics = {
        "sampled_count": int(sampled_count),
        "sdf_record_count": int(sdf_record_count),
        "valid_count": int(valid_count),
        "validity": safe_ratio(valid_count, sampled_count),
        "connected_count": int(connected_count),
        "connected_ratio": safe_ratio(connected_count, valid_count),
        "unique_count": int(unique_count),
        "uniqueness": safe_ratio(unique_count, valid_count),
        "novel_count": int(novel_count),
        "novelty": safe_ratio(novel_count, valid_count),
        "diversity": float(diversity),
        "training_unique_smiles": int(len(training_smiles)),
    }

    rows = [
        {
            "Metric": "Sampled molecules",
            "Value": format_value(metrics["sampled_count"]),
            "Explanation": "Number of molecules sampled from the generative model.",
        },
        {
            "Metric": "Valid molecules",
            "Value": format_value(metrics["valid_count"]),
            "Explanation": "Number of generated molecules that can be legally parsed and sanitized by RDKit.",
        },
        {
            "Metric": "Validity ↑",
            "Value": format_value(metrics["validity"], is_ratio=True),
            "Explanation": "Ratio of valid molecules to sampled molecules.",
        },
        {
            "Metric": "Connected ↑",
            "Value": format_value(metrics["connected_ratio"], is_ratio=True),
            "Explanation": "Ratio of single-component molecules to valid molecules.",
        },
        {
            "Metric": "Unique molecules",
            "Value": format_value(metrics["unique_count"]),
            "Explanation": "Number of unique valid molecules after canonical SMILES deduplication.",
        },
        {
            "Metric": "Uniqueness ↑",
            "Value": format_value(metrics["uniqueness"], is_ratio=True),
            "Explanation": "Ratio of unique molecules to valid molecules.",
        },
        {
            "Metric": "Novel molecules",
            "Value": format_value(metrics["novel_count"]),
            "Explanation": "Number of unique generated molecules not found in the training set.",
        },
        {
            "Metric": "Novelty ↑",
            "Value": format_value(metrics["novelty"], is_ratio=True),
            "Explanation": "Ratio of novel molecules to valid molecules.",
        },
        {
            "Metric": "Diversity ↑",
            "Value": format_value(metrics["diversity"], is_ratio=True),
            "Explanation": "Average pairwise structural dissimilarity among unique generated molecules based on Morgan fingerprints.",
        },
    ]

    return pd.DataFrame(rows), metrics


def set_cell_shading(cell, fill: str):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_cell_text_format(cell, bold: bool = False, font_size: int = 10):
    for paragraph in cell.paragraphs:
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if len(cell.text) < 18 else WD_ALIGN_PARAGRAPH.LEFT
        for run in paragraph.runs:
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
            run.font.size = Pt(font_size)
            run.bold = bold


def set_table_borders(table):
    tbl = table._tbl
    tbl_pr = tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for border_name in ["top", "left", "bottom", "right", "insideH", "insideV"]:
        border = OxmlElement(f"w:{border_name}")
        border.set(qn("w:val"), "single")
        border.set(qn("w:sz"), "8")
        border.set(qn("w:space"), "0")
        border.set(qn("w:color"), "000000")
        borders.append(border)
    tbl_pr.append(borders)


def add_quality_table_to_docx(table_df: pd.DataFrame, output_docx: Path, input_docx: Optional[Path] = None):
    if input_docx and input_docx.exists():
        document = Document(str(input_docx))
    else:
        document = Document()

    section = document.sections[-1]
    section.top_margin = Cm(2.2)
    section.bottom_margin = Cm(2.2)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2.5)

    title = document.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title.add_run(TABLE_TITLE)
    title_run.bold = True
    title_run.font.name = "Times New Roman"
    title_run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    title_run.font.size = Pt(11)

    table = document.add_table(rows=1, cols=3)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    set_table_borders(table)

    headers = ["Metric", "Value", "Explanation"]
    widths = [Cm(4.2), Cm(3.0), Cm(9.6)]

    header_cells = table.rows[0].cells
    for idx, header in enumerate(headers):
        header_cells[idx].text = header
        header_cells[idx].width = widths[idx]
        header_cells[idx].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        set_cell_shading(header_cells[idx], "D9EAF7")
        set_cell_text_format(header_cells[idx], bold=True, font_size=10)

    for _, row in table_df.iterrows():
        cells = table.add_row().cells
        values = [row["Metric"], row["Value"], row["Explanation"]]
        for idx, value in enumerate(values):
            cells[idx].text = str(value)
            cells[idx].width = widths[idx]
            cells[idx].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            set_cell_text_format(cells[idx], bold=False, font_size=10)

    note = document.add_paragraph()
    note_run = note.add_run(
        "Note: Validity is computed using RDKit sanitization. Diversity is calculated as 1 minus the mean pairwise Tanimoto similarity among unique generated molecules."
    )
    note_run.font.name = "Times New Roman"
    note_run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    note_run.font.size = Pt(9)

    output_docx.parent.mkdir(parents=True, exist_ok=True)
    document.save(str(output_docx))


def main():
    parser = argparse.ArgumentParser(description="Generate Table 4-2 molecular quality statistics and insert it into a DOCX file.")
    parser.add_argument("--generated_sdf", required=True, help="Path to generated molecule SDF.")
    parser.add_argument("--training_csv", required=True, help="Path to training/reference CSV with a SMILES column.")
    parser.add_argument("--output_docx", required=True, help="Output DOCX path.")
    parser.add_argument("--input_docx", default="", help="Optional existing DOCX. If provided, the table is appended to it.")
    parser.add_argument("--smiles_col", default="smiles", help="SMILES column name in the training CSV.")
    parser.add_argument("--sampled_count", type=int, default=0, help="Raw model sampling count. If 0, the script uses SDF record count.")
    parser.add_argument("--max_diversity_pairs", type=int, default=0, help="Optional random pair cap for diversity. 0 means all pairs.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out_csv", default="", help="Optional CSV output path for the table.")
    parser.add_argument("--out_json", default="", help="Optional JSON output path for raw metrics.")
    args = parser.parse_args()

    generated_sdf = Path(args.generated_sdf)
    training_csv = Path(args.training_csv)
    output_docx = Path(args.output_docx)
    input_docx = Path(args.input_docx) if args.input_docx else None

    table_df, metrics = compute_quality_table(
        generated_sdf=generated_sdf,
        training_csv=training_csv,
        smiles_col=args.smiles_col,
        sampled_count=args.sampled_count,
        max_diversity_pairs=args.max_diversity_pairs,
        seed=args.seed,
    )

    add_quality_table_to_docx(table_df, output_docx=output_docx, input_docx=input_docx)

    out_csv = Path(args.out_csv) if args.out_csv else output_docx.with_suffix(".csv")
    out_json = Path(args.out_json) if args.out_json else output_docx.with_suffix(".json")

    table_df.to_csv(out_csv, index=False, encoding="utf-8-sig")
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, ensure_ascii=False)

    print(f"Saved DOCX: {output_docx}")
    print(f"Saved CSV: {out_csv}")
    print(f"Saved JSON: {out_json}")
    print(json.dumps(metrics, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
